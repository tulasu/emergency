def run(name, cases, expect_answer=True):
    ok = wrong = absta = 0
    fails = []
    for sc, phrase, exp in cases:
        h = Matcher(sc).match(normalize(phrase))
        if h.status != "answered":
            absta += 1
            if expect_answer:
                fails.append(f"    переспрос  {phrase:34} [{sc.scenario_id[:8]}] s={h.score:.2f}")
        elif expect_answer and h.fact_key == exp:
            ok += 1
        else:
            wrong += 1
            fails.append(f"    НЕВЕРНО    {phrase:34} [{sc.scenario_id[:8]}] "
                         f"-> {h.fact_key} s={h.score:.2f} m={h.margin:.2f}")
    n = len(cases)
    good = ok if expect_answer else absta
    print(f"{name}: {good}/{n} правильно | неверный факт {wrong} | "
          f"переспрос {absta if expect_answer else n - absta - wrong}")
    for f in fails:
        print(f)
    return ok, wrong, absta, n


