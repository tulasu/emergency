_REFINE_WORD = re.compile(
    r"\b(точн(ее|ей)|поточнее|именно|конкретн(ее|ей)|уточните|"
    r"а именно|полностью|целиком|дословно)\b"
)
_LEADING_AND = re.compile(r"^\s*(?:а|и|ну а|а вот)\s+", re.I)


def is_refinement(text: str) -> bool:
    """Реплика, которая сама по себе темы не задаёт и висит на предыдущей.

    «А корпус?», «точнее?», «а номер какой» — оператор уточняет то же самое
    сведение, о котором только что шла речь.
    """
    low = text.strip().lower().replace("ё", "е")
    topical = normalize.topical_lemmas(low)

    # «точнее?» — уточнение, «где именно горит, на каком этаже» — нет:
    # у второй реплики своя тема, слово «именно» в ней служебное
    if _REFINE_WORD.search(low):
        return len(topical) <= 1

    if not _LEADING_AND.match(low):
        return False
        # «а» в начале + короткий хвост: продолжение той же темы.
        # «а что случилось» темой распоряжается само — это не уточнение.
    tail = _LEADING_AND.sub("", low)
    ws = normalize.words(tail)
    if not ws or len(ws) > 4:
        return False
        # «а где вы находитесь» и «а сколько этажей» задают тему сами, «а корпус?»
        # и «а какой именно?» — нет. «Сколько» в исключения не входит: вопрос
        # с ним всегда о своём предмете, а не о предыдущем.
    return not ({normalize.lemma(w) for w in ws} & (_Q_WORDS - {"какой"}))


_REPEAT = re.compile(
    r"\b(повторите|повторить|еще раз|ещё раз|не расслышал\w*|не понял\w*|"
    r"что вы сказали|громче|не записал\w*|можете сказать|скажите ещё|"
    r"скажите еще|продиктуйте ещё|продиктуйте еще)\b"
)


def is_repeat_request(text: str) -> bool:
    """Просьба повторить последний ответ, а не новый вопрос."""
    return bool(_REPEAT.search(text.lower().replace("ё", "е")))


def repeat_without_topic(text: str) -> bool:
    """Просьба повторить, у которой нет собственной темы.

    «Можете повторить этаж?» — тема есть, это обычный вопрос про этаж.
    «Да, не записала, можете сказать?» — темы нет, повторить надо то же
    самое. Проверять надо остаток ПОСЛЕ вырезания самой просьбы: иначе
    «не записала» само сойдёт за тему.
    """
    low = text.lower().replace("ё", "е")
    if not _REPEAT.search(low):
        return False
    rest = _REPEAT.sub(" ", low)
    return not normalize.topical_lemmas(rest)
