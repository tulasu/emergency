# -*- coding: utf-8 -*-
"""
Детерминированный слой понимания: что оператор сделал репликой.

Микросекунды, ноль зависимостей от моделей. Здесь же распознаётся эллипсис —
короткое уточнение вроде «а корпус?», смысл которого держится на предыдущем
ответе заявителя. Сам контекст живёт в каскаде, правила знают только форму.
"""

from __future__ import annotations

import re

from ..types import Act
from . import normalize

# ----------------------------------------------------------- речевые акты

SPEECH_ACTS: dict[str, re.Pattern] = {
    # Одно существительное сообщением о выезде не является: «наряд куда
    # подъезжать?» — это вопрос оператора, а не объявление. Нужен глагол.
    "выезд": re.compile(
        r"\b(выехал|выезжа|направ(ил|ля)|"
        r"(бригад|наряд|расчёт|расчет|скор)\w*\s+\S*\s?"
        r"(выехал|направ|высла|ед[еу]т|в пути|прибуд|уже)|"
        r"помощь (уже )?ид|уже ед|скор(ая|ую) (выслал|направ)|"
        # STT: «служба уже в пути», «передаю вашу заявку», «мы с вами свяжемся»
        r"\bв пути\b|переда(ю|м|л)\w* (ваш\w* )?(заявк|информаци|вызов|данн|служб)|"
        r"с вами свяж|перезвон)"
    ),
    "успокоение": re.compile(
        r"\b(успокой|не паник|оставайтесь|остават?ься на (месте|линии)|"
        r"не клад[иі]те|не вешайте|ждите|подождите на линии)"
    ),
    "инструкция": re.compile(
        r"\b(не подходите|не пытайтесь|не включайте|не курите|не открывайте|"
        r"отойдите|выйдите|покиньте|перекройте|не тушите|встречайте|встреть|"
        r"уходите|не пользуйтесь|пользуйтесь лестниц|предупредите|"
        r"закройте|проветри)"
    ),
    # STT пишет числа словами: «служба сто двенадцать», «сто двенадцать говорите»
    "приветствие": re.compile(
        r"(служб\w* (112|сто двенадцать)|единая служба|служба спасения|"
        r"оператор \d|слушаю вас|^(112|сто двенадцать)\b|"
        r"\b(112|сто двенадцать) (слушаю|говорите)|^ал+[оеё]\b|здравствуйте)"
    ),
    "прощание": re.compile(
        r"\b(до свидания|всего доброго|вызов принят|заявка принята)"
    ),
}

# Реплика целиком из таких слов — оператор принял ответ, а не спросил.
# «хорошо, можете сказать адрес» сюда не попадает: там есть вопрос.
_ACK_WORDS = frozenset("""
хорошо хороо ладно понял поняла понятно ясно ага угу так ок окей отлично
супер спасибо большое записал записала записываю принял приняла я вас
все всё да вот
""".split())
_ACK_LEAD = re.compile(
    r"^((ага|угу|так|хорошо|ладно|понятно|ясно|супер|отлично|окей|ок|"
    r"спасибо|я (вас )?понял[а]?|понял[а]?|записал[а]?)[\s,.!]+)+"
)


def is_ack(text: str) -> bool:
    """«Хорошо», «я понял, спасибо» — принято, заявителю хватит «да»."""
    ws = normalize.words(text.lower().replace("ё", "е"))
    return bool(ws) and all(w in _ACK_WORDS for w in ws)


def strip_ack_lead(text: str) -> str:
    """«ага хорошо пострадавшие есть» -> «пострадавшие есть»."""
    out = _ACK_LEAD.sub("", text.lower().replace("ё", "е")).strip()
    return out or text


_CONFIRM = re.compile(
    r"\b(верно|правильно|значит|то есть|уточняю|"
    r"подтвержда|подтвердите|точно|я записал|записываю)\b"
)

# глаголы и наречия, с которых начинается вопрос без вопросительного слова
_Q_OPENERS = frozenset(
    {
        "есть",
        "видеть",
        "слышать",
        "мочь",
        "знать",
        "находиться",
        "гореть",
        "далеко",
        "живой",
        "нужно",
        "стоять",
        "лежать",
        "дышать",
    }
)
_Q_IMPERATIVES = frozenset(
    {
        "представиться",
        "назвать",
        "сказать",
        "уточнить",
        "сообщить",
        "описать",
        "продиктовать",
        "повторить",
        "давать",
        "дать",
    }
)
_Q_WORDS = frozenset(
    {
        "что",
        "где",
        "когда",
        "как",
        "какой",
        "сколько",
        "кто",
        "чей",
        "чем",
        "чего",
        "который",
        "куда",
        "откуда",
    }
)


def speech_act(text: str) -> str | None:
    """Речевой акт, если реплика им исчерпывается.

    «Служба 112, что у вас случилось?» — приветствие плюс вопрос. Вопрос
    важнее: ответить на него «хорошо, поняла» значит проглотить ход.
    """
    low = text.lower().replace("ё", "е")
    if is_ack(strip_ritual(low)):
        return "подтверждение"
    for kind, pat in SPEECH_ACTS.items():
        m = pat.search(low)
        if not m:
            continue
        if kind in ("приветствие", "прощание"):
            rest = low[: m.start()] + " " + low[m.end() :]
            if _is_question(rest):
                return None  # после приветствия идёт настоящий вопрос
        elif kind == "выезд" and ("?" in text or _is_question(low)):
            # о выезде сообщают, а не спрашивают: «какая бригада приедет?»
            # и «наряд куда подъезжать?» — вопросы оператора
            return None
        return kind
    return None


_OPEN_Q = re.compile(
    r"\b(что|как|какой|какая|какие|сколько|кто|куда|откуда|"
    r"где|опишите|расскажите|назовите|уточните)\b"
)
_YESNO_Q = re.compile(
    r"\b(ли|есть|видите|слышите|чувствуете|пахнет|"
    r"можете|нужна|требуется|остались?|горит ли)\b"
)


def question_form(text: str) -> str:
    """Открытый вопрос, вопрос на да/нет или неопределённый.

    «Что случилось?» нельзя ответить слотом «да/нет», «Газом пахнет?» —
    слотом-описанием. Форма вопроса сужает круг слотов не хуже лексики.
    """
    low = text.lower().replace("ё", "е")
    if " ли " in f" {low } ":
        return "yesno"
    open_hit = bool(_OPEN_Q.search(low))
    yesno_hit = bool(_YESNO_Q.search(low))
    if open_hit and not yesno_hit:
        return "open"
    if yesno_hit and not open_hit:
        return "yesno"
    return "any"


def strip_ritual(text: str) -> str:
    """Убирает приветствие и прощание, оставляя суть реплики.

    «Служба 112, что у вас случилось?» -> «что у вас случилось?»
    """
    low = text
    for kind in ("приветствие", "прощание"):
        # «алло здравствуйте служба сто двенадцать» — несколько вхождений
        for _ in range(4):
            m = SPEECH_ACTS[kind].search(low.lower().replace("ё", "е"))
            if not m:
                break
            low = (low[: m.start()] + " " + low[m.end() :]).strip(" ,.;-")
    low = strip_ack_lead(low) if low else low
    return low or text


def _is_question(text: str) -> bool:
    """Вопрос ли это, без оглядки на речевые акты."""
    low = text.lower().replace("ё", "е")
    ws = normalize.words(low)
    lemmas = {normalize.lemma(w) for w in ws}
    return bool(
        lemmas & _Q_WORDS
        or lemmas & _Q_IMPERATIVES
        or " ли " in f" {low } "
        or _opener_position(ws)
    )


def detect_act(text: str) -> Act:
    low = text.lower().replace("ё", "е")
    if speech_act(low):
        return Act.SPEECH_ACT

    if _CONFIRM.search(low):
        return Act.CONFIRM

    return Act.ASK if ("?" in text or _is_question(low)) else Act.ASSERT


def _opener_position(ws: list[str]) -> bool:
    """Вопрос без вопросительного слова.

    Оператор одинаково часто говорит «есть пострадавшие» и «пострадавшие
    есть» — глагол стоит либо в начале, либо в конце, так что смотрим оба
    края. «Вы видите пламя» — глагол вторым, после местоимения.
    """
    if not ws:
        return False
    edges = [normalize.lemma(w) for w in (ws[:2] + ws[-1:])]
    return bool(set(edges) & _Q_OPENERS)

