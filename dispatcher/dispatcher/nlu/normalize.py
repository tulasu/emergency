_WORD = re.compile(r"^[\w\d]+$")
# «ВАЗ-2110», «А128АА-177», «дом-корпус» приходят одним токеном с дефисом и
# целиком отбраковывались как несловесные — вместе с маркой машины и номером
_HYPHEN = re.compile(r"[-–—/]")
_SPLIT = re.compile(r"\s*(?:[,;?!]|\bа также\b|\bа ещё\b|\bа еще\b|\bи\b)\s*")


@functools.lru_cache(maxsize=200_000)
def lemma(word: str) -> str:
    return _morph.parse(word)[0].normal_form.replace("ё", "е")


def words(text: str) -> list[str]:
    out: list[str] = []
    for t in tokenize(text):
        for part in _HYPHEN.split(t.text):
            if part and _WORD.match(part):
                out.append(part.lower().replace("ё", "е"))
    return out


def content_lemmas(text: str) -> set[str]:
    """Леммы, по которым реплика сопоставляется со слотом."""
    out = set()
    for w in words(text):
        if w.isdigit():
            continue
        lm = lemma(w)
        # местоимения короткие («вы», «он», «их»), фильтр длины их съедает —
        # а различают они заявителя и пострадавшего
        if lm not in STOP and (len(lm) > 2 or lm in PERSON_WORDS):
            out.add(lm)
    return out


def topical_lemmas(text: str) -> set[str]:
    """Леммы темы, без вопросительных слов.

    По ним отличается «не расслышала» от «не знаю»: у реплики «а что?» темы
    нет вовсе, у реплики «а что с крышей?» — есть. Местоимения сюда тоже не
    входят: «а вы что?» темы не задаёт.
    """
    return content_lemmas(text) - QUESTION_WORDS - PERSON_WORDS


def numbers(text: str) -> set[int]:
    """Числа реплики — и цифрами, и словами, включая составные.

    «Тридцать семь» это 37, а не 30 и 7 по отдельности. Без сложения ломается
    любой переспрос с номером дома, этажа или возраста: оператор зачитывает
    словами, а в ответе заявителя стоит цифра.
    """
    run: list[int] = []
    out: set[int] = set()

    def flush() -> None:
        if not run:
            return
            # «сто двадцать три» = 100 + 20 + 3, но «три пять» остаются врозь
        descending = all(run[i] > run[i + 1] for i in range(len(run) - 1))
        if len(run) > 1 and descending:
            out.add(sum(run))
        out.update(run)
        run.clear()

    for w in words(text):
        if w.isdigit() and len(w) <= 4:
            flush()
            out.add(int(w))
            continue
        n = CARDINALS.get(w) or CARDINALS.get(lemma(w))
        if n is None:
            flush()
        else:
            run.append(n)
    flush()
    return out


def segments(text: str) -> list[str]:
    """Составной вопрос по частям плюс целая фраза.

    «Адрес назовите и есть ли пострадавшие» — два вопроса в одной реплике,
    оба должны получить ответ.
    """
    parts = [p.strip() for p in _SPLIT.split(text) if len(p.strip()) > 2]
    whole = text.strip()
    if whole and whole not in parts:
        parts.append(whole)
    return list(dict.fromkeys(parts))
