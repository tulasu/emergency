# -*- coding: utf-8 -*-
"""
Нормализация реплики: токены, леммы, числа, сегменты.

Единственное место, где ядро знает про морфологию русского языка. Всё
остальное работает с готовыми леммами и не подозревает о pymorphy.
"""

from __future__ import annotations

import functools
import re

import pymorphy3
from razdel import tokenize

_morph = pymorphy3.MorphAnalyzer()

# Вопросительные слова темы не задают, но именно они решают, о каком слоте
# речь: «что случилось» и «где случилось» отличаются только ими. Поэтому в
# оценке они участвуют наравне с остальными и лежат отдельным множеством.
QUESTION_WORDS = frozenset("""
что где когда как какой сколько кто чей чем чего который куда откуда
""".split())

# Местоимения лица темы не задают, но различают, о ком речь: «как ВАС зовут»
# и «как ЕЁ зовут» отличаются только ими, а это разные слоты — ФИО заявителя
# и ФИО пострадавшего. Поэтому в оценке они участвуют, а из темы исключаются.
PERSON_WORDS = frozenset("""
вы ваш ты твой он она они его ее их мы нас нам я мой наш сам себя
""".split())

# Служебные слова: ни темы, ни слота не задают.
STOP = frozenset("""
быть есть это тот там тут сейчас дело или и а но же бы ли да нет
правильно понять значит верно точно уточнять подтверждать записывать
повторять понимать
не ни в на с у к по до от за о об для из про над под при через
мочь нужно надо пожалуйста ещё еще уже очень весь свой
сказать назвать уточнить сообщить описать повторить продиктовать
давать дать говорить слышать
видеть видно увидеть
""".split())

# «представиться» служебным НЕ считается: это и есть запрос ФИО.

