# -*- coding: utf-8 -*-
"""
Морфология. Заменяет всю самодельную работу с основами.

pymorphy3 сводит «этажей» и «этаже» к «этаж», оставляя «этажность»
отдельной леммой — то различие, которое раньше кодировалось префиксами.
razdel режет фразу, не ломая «дом 11, стр. 2» и «Иванова И. И.».
"""
from __future__ import annotations

import functools
import re

import pymorphy3
from razdel import tokenize

_morph = pymorphy3.MorphAnalyzer()

# служебные слова: не несут темы вопроса
STOP = {
    "что", "где", "когда", "как", "какой", "сколько", "кто", "чей", "чем",
    "быть", "есть", "это", "тот", "там", "сейчас", "дело", "или", "и", "а", "но", "же", "бы",
    "не", "ни", "в", "на", "с", "у", "к", "по", "до", "от", "за", "о", "об",
    "для", "ли", "да", "нет", "мочь", "нужно", "надо", "пожалуйста", "ещё",
    "еще", "уже", "очень", "сам", "весь", "свой", "мой", "наш",
    # местоимения темы не задают: «что у вас случилось» — не вопрос о том, где заявитель
    "вы", "ваш", "ты", "твой",
    # глаголы-просьбы: тему не задают
    "сказать", "назвать", "уточнить", "сообщить", "описать", "повторить",
    "продиктовать",   # «представиться» НЕ служебное: это и есть запрос ФИО
    # глаголы восприятия: тему задаёт объект («пламя видите» — про пламя)
    "видеть", "видно", "увидеть",
}

CARDINALS = {
    "один": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14,
    "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19, "двадцать": 20, "тридцать": 30, "сорок": 40,
    "пятьдесят": 50, "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80,
    "девяносто": 90, "сто": 100,
    "первый": 1, "второй": 2, "третий": 3, "четвёртый": 4, "четвертый": 4,
    "пятый": 5, "шестой": 6, "седьмой": 7, "восьмой": 8, "девятый": 9,
    "десятый": 10, "одиннадцатый": 11, "двенадцатый": 12, "тринадцатый": 13,
    "четырнадцатый": 14, "пятнадцатый": 15, "семнадцатый": 17,
}


@functools.lru_cache(maxsize=100_000)
def lemma(word: str) -> str:
    return _morph.parse(word)[0].normal_form


def words(text: str) -> list[str]:
    return [t.text.lower().replace("ё", "е") for t in tokenize(text)
            if re.match(r"^[\w\d]+$", t.text)]


def content_lemmas(text: str) -> set[str]:
    """Леммы, которые задают тему вопроса."""
    out = set()
    for w in words(text):
        if w.isdigit():
            continue
        lm = lemma(w)
        if lm not in STOP and len(lm) > 2:
            out.add(lm)
    return out


def topical_lemmas(text: str) -> set[str]:
    """То же, что content_lemmas: по ним решаем, есть ли вообще тема."""
    return content_lemmas(text)


def numbers(text: str) -> set[int]:
    out = {int(w) for w in words(text) if w.isdigit() and len(w) <= 4}
    for w in words(text):
        lm = lemma(w)
        if lm in CARDINALS:
            out.add(CARDINALS[lm])
        elif w in CARDINALS:
            out.add(CARDINALS[w])
    return out


def segments(text: str) -> list[str]:
    """Режем многосоставный вопрос, целую фразу тоже возвращаем."""
    parts = re.split(r"\s*(?:[,;?]|\bа также\b|\bа ещё\b|\bа еще\b|\bи\b)\s*", text)
    parts = [p.strip() for p in parts if len(p.strip()) > 2]
    if text.strip() not in parts:
        parts.append(text.strip())
    return list(dict.fromkeys(parts))
