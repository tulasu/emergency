import { ruCount } from './ru-count';

describe('ruCount', () => {
  it('picks one/few/many forms', () => {
    expect(ruCount(1, 'учётная запись', 'учётные записи', 'учётных записей')).toBe('1 учётная запись');
    expect(ruCount(2, 'учётная запись', 'учётные записи', 'учётных записей')).toBe('2 учётные записи');
    expect(ruCount(5, 'учётная запись', 'учётные записи', 'учётных записей')).toBe('5 учётных записей');
    expect(ruCount(21, 'учётная запись', 'учётные записи', 'учётных записей')).toBe('21 учётная запись');
    expect(ruCount(12, 'учётная запись', 'учётные записи', 'учётных записей')).toBe('12 учётных записей');
  });
});
